def render_harness_scaffold(attack: dict[str, Any], harness_name: str) -> str:
    """Scaffold for a missing harness, pre-filled with the attack's own
    data (entry point, controlled inputs, probed asset, cross assets) so
    a human/orchestrator only fills the protocol plumbing."""
    slug = test_slug(attack.get("attack_id", ""))
    entry = attack.get("entry_point", {}).get("function", "?")
    inputs = ", ".join(
        i.get("expression", "?") for i in attack.get("controlled_inputs", [])
    ) or "none recorded"
    blind = (attack.get("expected_consequence") or {}).get("cross_asset_blind_spot") or {}
    probed = blind.get("probed_asset", "the asset the delta check measures")
    cross = ", ".join(blind.get("other_assets") or []) or "none recorded"
    plan = attack.get("validator_plan") or {}

    return _SCAFFOLD_TEMPLATE.format(
        name=harness_name,
        slug=slug,
        entry=_escape(entry),
        inputs=_escape(inputs),
        probed=_escape(str(probed)),
        cross=_escape(cross),
        attacker_setup=_escape(plan.get("attacker_setup", "")),
    )


