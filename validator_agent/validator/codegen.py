"""Foundry test synthesis from an attack hypothesis.

Division of responsibility (keeps the engine generic):

  ENGINE (this module) generates, purely from the attack record:
    - the IProtocolHarness interface (setup + entry invocation contract)
    - a generic attacker contract: plays the approved-spender role and
      the callback-receiver role (ERC-721/1155 hooks) that drains the
      probed asset when a cross asset lands on it
    - the test driver with exactly two executable questions:
        test_attack_call_succeeds : did the attack sequence complete
                                    (confirm precondition)?
        test_attacker_gains       : did the attacker end up with the
                                    probed asset or a cross asset?
      both pass -> CONFIRM; a failure is an executed REJECT reason
    - a harness SCAFFOLD (with the attack's own data filling the TODO
      lines) when no harness was supplied

  HARNESS (supplied as DATA per repository) implements IProtocolHarness:
  protocol deployment, funding, and the entry invocation with attacker-
  chosen inputs. Nothing in the engine knows any protocol name.

Only generic token-standard vocabulary (IERC20 / receiver hooks) and the
canonical Foundry cheatcode address appear in generated code.
"""

from __future__ import annotations

import re
from typing import Any

CHEATCODE_ADDRESS = "0x7109709ECfa91a80626fF3989D68f67F5b1DD12D"


def test_slug(attack_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", attack_id) or "Attack"


def render_test(attack: dict[str, Any], harness_contract: str,
                harness_file: str = "") -> str:
    """Render the Foundry test file for one attack."""
    slug = test_slug(attack.get("attack_id", ""))
    plan = attack.get("validator_plan") or {}
    consequence = attack.get("expected_consequence") or {}
    blind = consequence.get("cross_asset_blind_spot") or {}
    has_cross = bool(blind.get("other_assets"))

    gain_check = _GAIN_WITH_CROSS if has_cross else _GAIN_PROBED_ONLY
    harness_import = (
        f'import {{{harness_contract}}} from "./{harness_file}";'
        if harness_file else ""
    )

    return _TEST_TEMPLATE.format(
        slug=slug,
        harness=harness_contract,
        harness_import=harness_import,
        cheatcode=CHEATCODE_ADDRESS,
        gain_check=gain_check,
        confirm_if=_escape(plan.get("confirm_if", "")),
        reject_if=_escape(plan.get("reject_if", "")),
        probed_asset=_escape(blind.get("probed_asset", "probed asset")),
        cross_names=_escape(", ".join(blind.get("other_assets") or [])),
    )


def _escape(text: str) -> str:
    return (text or "").replace("\\", "\\\\").replace('"', '\\"')


